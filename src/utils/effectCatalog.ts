const ALL_EFFECT_CATALOG: EffectCatalogEntry[] = [
  ...EFFECT_CATALOG,
  ...FX34_CATALOG.filter((item) => item.type !== 'disco').map((item) => ({
    type: item.type,
    name: item.name,
    icon: item.icon,
    category: 'fx34' as TimelineEffectCategory,
    defaultIntensity: item.defaultIntensity,
    defaultOpacity: item.defaultOpacity,
    lowHint: item.lowHint,
    medHint: item.medHint,
    highHint: item.highHint,
  })),
];

export function getEffectCatalogEntry(
  type: TimelineEffectType
): EffectCatalogEntry {
  return (
    ALL_EFFECT_CATALOG.find((e) => e.type === type) ?? ALL_EFFECT_CATALOG[0]
  );
}

export function getEffectIntensityLabel(
  type: TimelineEffectType,
  intensity: number
): string {
  const entry = getEffectCatalogEntry(type);
  if (intensity < 0.4) return entry.lowHint;
  if (intensity < 0.75) return entry.medHint;
  return entry.highHint;
}
